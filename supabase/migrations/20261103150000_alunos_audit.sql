-- Phase 1A / step 6: audit log for student data (who, when, table, row, old/new JSON).
-- Only admins can read it; nobody writes it from the client (triggers are security definer).
-- CPF is masked inside the JSON. Health values are stored as-is (admin-only table).

create table if not exists alunos.auditoria (
  id bigint generated by default as identity primary key,
  em timestamptz not null default now(),
  usuario uuid,
  usuario_email text,
  tabela text not null,
  operacao text not null,
  registro_id text,
  antes jsonb,
  depois jsonb
);
create index if not exists alunos_auditoria_registro_ix on alunos.auditoria (tabela, registro_id, em desc);

alter table alunos.auditoria enable row level security;
revoke all on alunos.auditoria from anon;

create or replace function alunos.audit_mask(j jsonb)
returns jsonb
language sql
immutable
set search_path = ''
as $$
  select case
    when j ? 'cpf' and j ->> 'cpf' is not null
      then jsonb_set(j, '{cpf}', to_jsonb('***.***.***-' || right(j ->> 'cpf', 2)))
    else j
  end;
$$;

create or replace function alunos.audit_row()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_old jsonb;
  v_new jsonb;
  v_id text;
begin
  if tg_op in ('UPDATE', 'DELETE') then v_old := alunos.audit_mask(to_jsonb(old)); end if;
  if tg_op in ('INSERT', 'UPDATE') then v_new := alunos.audit_mask(to_jsonb(new)); end if;

  -- ignore no-op updates (only the touch timestamp changed)
  if tg_op = 'UPDATE' and (v_old - 'atualizado_em') = (v_new - 'atualizado_em') then
    return null;
  end if;

  v_id := coalesce(
    to_jsonb(coalesce(new, old)) ->> 'aluno_id',
    to_jsonb(coalesce(new, old)) ->> 'id');

  insert into alunos.auditoria (usuario, usuario_email, tabela, operacao, registro_id, antes, depois)
  values (auth.uid(), nullif(lower(coalesce(auth.jwt() ->> 'email', '')), ''),
          tg_table_name, tg_op, v_id, v_old, v_new);
  return null;
end $$;

revoke all on function alunos.audit_mask(jsonb) from public, anon, authenticated;
revoke all on function alunos.audit_row() from public, anon, authenticated;

do $$
declare t text;
begin
  foreach t in array array['alunos', 'dados_pessoais', 'aluno_saude', 'aluno_igreja',
                           'matriculas', 'ciclo_status', 'aluno_tutores']
  loop
    execute format('drop trigger if exists trg_audit on alunos.%I', t);
    execute format(
      'create trigger trg_audit after insert or update or delete on alunos.%I
         for each row execute function alunos.audit_row()', t);
  end loop;
end $$;
