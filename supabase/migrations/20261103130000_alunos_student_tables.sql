-- Phase 1A / step 4: student tables. Documents/address/family stay in the existing
-- alunos.dados_pessoais (no duplicate table). Health is separate and restricted.

create table if not exists alunos.aluno_igreja (
  aluno_id uuid primary key references alunos.alunos (id) on delete cascade,
  igreja_anterior text,
  igreja_atual text,
  atualizado_em timestamptz not null default now()
);

create table if not exists alunos.aluno_saude (
  aluno_id uuid primary key references alunos.alunos (id) on delete cascade,
  plano_saude text,
  tipo_sanguineo text check (tipo_sanguineo in ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')),
  limitacoes_medicas text,
  medicamento_continuo text,
  alergia text,
  restricao_alimentar text,
  enfermidades text,
  atualizado_em timestamptz not null default now()
);

create table if not exists alunos.aluno_status_historico (
  id bigint generated by default as identity primary key,
  aluno_id uuid not null references alunos.alunos (id) on delete cascade,
  status text not null,
  desde timestamptz not null default now(),
  motivo text,
  registrado_por uuid
);
create index if not exists aluno_status_historico_aluno_ix on alunos.aluno_status_historico (aluno_id, desde desc);

-- Directory of people who can be assigned to students (permissions live in public.staff_roles;
-- the two are linked by e-mail).
create table if not exists alunos.equipe (
  id uuid primary key default gen_random_uuid(),
  nome text not null,
  email text not null unique check (email = lower(btrim(email))),
  ativo boolean not null default true
);

create table if not exists alunos.equipe_casas (
  equipe_id uuid not null references alunos.equipe (id) on delete cascade,
  casa_id int not null references alunos.casas (id) on delete cascade,
  primary key (equipe_id, casa_id)
);

-- tutoria = tutor; mentoria = mentor (house leaders see their house through equipe_casas)
create table if not exists alunos.aluno_tutores (
  id uuid primary key default gen_random_uuid(),
  aluno_id uuid not null references alunos.alunos (id) on delete cascade,
  semestre_id uuid not null references alunos.semestres (id) on delete cascade,
  equipe_id uuid not null references alunos.equipe (id) on delete cascade,
  categoria text not null check (categoria in ('tutoria', 'mentoria')),
  unique (aluno_id, semestre_id, equipe_id, categoria)
);
create index if not exists aluno_tutores_equipe_ix on alunos.aluno_tutores (equipe_id);

alter table alunos.aluno_igreja enable row level security;
alter table alunos.aluno_saude enable row level security;
alter table alunos.aluno_status_historico enable row level security;
alter table alunos.equipe enable row level security;
alter table alunos.equipe_casas enable row level security;
alter table alunos.aluno_tutores enable row level security;

revoke all on alunos.aluno_igreja, alunos.aluno_saude, alunos.aluno_status_historico,
  alunos.equipe, alunos.equipe_casas, alunos.aluno_tutores from anon;

-- Keep atualizado_em fresh (same helper the existing alunos tables use).
drop trigger if exists trg_aluno_igreja_touch on alunos.aluno_igreja;
create trigger trg_aluno_igreja_touch before update on alunos.aluno_igreja
  for each row execute function selecao.touch_atualizado_em();
drop trigger if exists trg_aluno_saude_touch on alunos.aluno_saude;
create trigger trg_aluno_saude_touch before update on alunos.aluno_saude
  for each row execute function selecao.touch_atualizado_em();

-- Status history. Humans must go through alunos.change_status(), which sets the reason;
-- automation (service role, security-definer RPCs such as registrar_checkin) has no
-- end-user JWT and is exempt from the "reason required" rule.
create or replace function alunos.tg_status_history()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_reason text := nullif(btrim(coalesce(current_setting('app.status_reason', true), '')), '');
begin
  if tg_op = 'INSERT' then
    insert into alunos.aluno_status_historico (aluno_id, status, motivo, registrado_por)
    values (new.id, new.status, coalesce(v_reason, 'initial status'), auth.uid());
  elsif new.status is distinct from old.status then
    if auth.uid() is not null and v_reason is null then
      raise exception 'A reason is required to change a student status (use alunos.change_status)'
        using errcode = '22023';
    end if;
    insert into alunos.aluno_status_historico (aluno_id, status, motivo, registrado_por)
    values (new.id, new.status, coalesce(v_reason, 'automation'), auth.uid());
  end if;
  return new;
end $$;

revoke all on function alunos.tg_status_history() from public, anon, authenticated;

drop trigger if exists trg_alunos_status_history on alunos.alunos;
create trigger trg_alunos_status_history
  after insert or update of status on alunos.alunos
  for each row execute function alunos.tg_status_history();
