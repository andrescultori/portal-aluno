-- ---------------------------------------------------------------- pure formulas (the Excel parity target)
-- mean of the values that are neither null nor zero
create or replace function alunos.calc_media(p_valores numeric[])
returns numeric
language sql
immutable
set search_path = ''
as $$
  select avg(v) from unnest(p_valores) as v where v is not null and v <> 0;
$$;

create or replace function alunos.calc_tutoria(p_teoria numeric, p_pratica numeric, p_atividades numeric,
                                               p_projeto numeric, p_presenca numeric)
returns numeric
language sql
immutable
set search_path = ''
as $$
  select round(alunos.calc_media(array[p_teoria, p_pratica, p_atividades, p_projeto, p_presenca]), 1);
$$;

-- computed on the already rounded tutoria and mentoria
create or replace function alunos.calc_final(p_tutoria numeric, p_mentoria numeric)
returns numeric
language sql
immutable
set search_path = ''
as $$
  select round(alunos.calc_media(array[p_tutoria, p_mentoria]), 1);
$$;

create or replace function alunos.conceito_de(p_final numeric)
returns text
language sql
stable
set search_path = ''
as $$
  select c.nome from alunos.conceitos c where p_final is not null and c.minimo <= p_final
   order by c.minimo desc limit 1;
$$;

create or replace function alunos.aprovado_de(p_final numeric)
returns boolean
language sql
stable
set search_path = ''
as $$
  select case when p_final is null then null else p_final >= (select aprovacao from alunos.notas_config where id) end;
$$;

-- ---------------------------------------------------------------- internal building blocks
-- Mean per question across submitted evaluations (valor 1 ignored). Questions are keyed by
-- (category, group code, question order) so a cloned model version keeps lining up.
create or replace function alunos._perguntas_calc(p_aluno uuid, p_semestre uuid)
returns table (categoria text, grupo_codigo text, grupo_nome text, grupo_ordem smallint,
               pergunta_ordem smallint, texto text, media numeric, avaliadores int)
language sql
stable
security definer
set search_path = ''
as $$
  select m.categoria,
         g.codigo,
         (array_agg(g.nome order by m.versao desc))[1],
         min(g.ordem),
         p.ordem,
         (array_agg(p.texto order by m.versao desc))[1],
         avg(alunos.pontos(r.valor)),
         (count(alunos.pontos(r.valor)))::int
    from alunos.avaliacoes a
    join alunos.avaliacao_respostas r on r.avaliacao_id = a.id
    join alunos.avaliacao_perguntas p on p.id = r.pergunta_id
    join alunos.avaliacao_grupos g on g.id = p.grupo_id
    join alunos.avaliacao_modelos m on m.id = g.modelo_id
   where a.aluno_id = p_aluno and a.semestre_id = p_semestre and a.status = 'enviada'
   group by m.categoria, g.codigo, p.ordem
   order by m.categoria desc, min(g.ordem), p.ordem;
$$;

-- Team members expected to evaluate the student: explicit assignments, plus (Mentoria) the leaders of the student's house.
create or replace function alunos._avaliadores_esperados(p_aluno uuid, p_semestre uuid, p_categoria text)
returns table (equipe_id uuid)
language sql
stable
security definer
set search_path = ''
as $$
  select t.equipe_id
    from alunos.aluno_tutores t
    join alunos.equipe e on e.id = t.equipe_id
   where t.aluno_id = p_aluno and t.semestre_id = p_semestre and t.categoria = p_categoria and e.ativo
  union
  select ec.equipe_id
    from alunos.alunos a
    join alunos.equipe_casas ec on ec.casa_id = a.casa_id
    join alunos.equipe e on e.id = ec.equipe_id
   where p_categoria = 'mentoria' and a.id = p_aluno and e.ativo
     and exists (select 1 from public.staff_roles sr where sr.email = e.email and sr.role = 'lider_casa');
$$;

create or replace function alunos._nota_semestre(p_aluno uuid, p_semestre uuid, p_ate date default null)
returns table (
  teoria numeric, pratica numeric, atividades numeric, projeto numeric, presenca numeric,
  tutoria numeric, mentoria numeric, final numeric, conceito text, aprovado boolean,
  completo boolean, pendencias jsonb,
  tutoria_enviadas int, tutoria_esperados int, mentoria_enviadas int, mentoria_esperados int)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_teoria numeric;
  v_pratica numeric;
  v_mentoria numeric;
  v_atv record;
  v_prj record;
  v_prs record;
  v_tutoria numeric;
  v_final numeric;
  v_t_env int;
  v_t_esp int;
  v_t_falta int;
  v_m_env int;
  v_m_esp int;
  v_m_falta int;
  v_pend jsonb := '[]'::jsonb;
begin
  select avg(q.media) filter (where q.categoria = 'tutoria' and q.grupo_codigo = 'teoria'),
         avg(q.media) filter (where q.categoria = 'tutoria' and q.grupo_codigo = 'pratica'),
         round(avg(q.media) filter (where q.categoria = 'mentoria'), 1)
    into v_teoria, v_pratica, v_mentoria
    from alunos._perguntas_calc(p_aluno, p_semestre) q;

  select * into v_atv from alunos._atividades_calc(p_aluno, p_semestre);
  select * into v_prj from alunos._projeto_calc(p_aluno, p_semestre);
  select * into v_prs from alunos._presenca_calc(p_aluno, p_semestre, p_ate);

  v_tutoria := alunos.calc_tutoria(v_teoria, v_pratica, v_atv.atividades, v_prj.projeto, v_prs.presenca);
  v_final := alunos.calc_final(v_tutoria, v_mentoria);

  -- evaluators: submitted vs expected, per category
  select count(*)::int into v_t_env from alunos.avaliacoes a
   where a.aluno_id = p_aluno and a.semestre_id = p_semestre and a.categoria = 'tutoria' and a.status = 'enviada';
  select count(*)::int into v_t_esp from alunos._avaliadores_esperados(p_aluno, p_semestre, 'tutoria');
  select count(*)::int into v_t_falta from alunos._avaliadores_esperados(p_aluno, p_semestre, 'tutoria') x
   where not exists (select 1 from alunos.avaliacoes a
                      where a.aluno_id = p_aluno and a.semestre_id = p_semestre and a.categoria = 'tutoria'
                        and a.status = 'enviada' and a.avaliador_equipe_id = x.equipe_id);
  select count(*)::int into v_m_env from alunos.avaliacoes a
   where a.aluno_id = p_aluno and a.semestre_id = p_semestre and a.categoria = 'mentoria' and a.status = 'enviada';
  select count(*)::int into v_m_esp from alunos._avaliadores_esperados(p_aluno, p_semestre, 'mentoria');
  select count(*)::int into v_m_falta from alunos._avaliadores_esperados(p_aluno, p_semestre, 'mentoria') x
   where not exists (select 1 from alunos.avaliacoes a
                      where a.aluno_id = p_aluno and a.semestre_id = p_semestre and a.categoria = 'mentoria'
                        and a.status = 'enviada' and a.avaliador_equipe_id = x.equipe_id);

  -- what is missing
  if v_t_env = 0 then
    v_pend := v_pend || jsonb_build_array(jsonb_build_object('codigo', 'tutoria_sem_avaliacoes', 'esperados', v_t_esp));
  elsif v_t_falta > 0 then
    v_pend := v_pend || jsonb_build_array(jsonb_build_object(
      'codigo', 'tutoria_avaliadores_faltando', 'enviadas', v_t_env, 'esperados', v_t_esp, 'faltando', v_t_falta));
  end if;
  if v_m_env = 0 then
    v_pend := v_pend || jsonb_build_array(jsonb_build_object('codigo', 'mentoria_sem_avaliacoes', 'esperados', v_m_esp));
  elsif v_m_falta > 0 then
    v_pend := v_pend || jsonb_build_array(jsonb_build_object(
      'codigo', 'mentoria_avaliadores_faltando', 'enviadas', v_m_env, 'esperados', v_m_esp, 'faltando', v_m_falta));
  end if;
  if v_atv.total = 0 then
    v_pend := v_pend || jsonb_build_array(jsonb_build_object('codigo', 'atividades_nao_cadastradas'));
  elsif v_atv.com_nota = 0 then
    v_pend := v_pend || jsonb_build_array(jsonb_build_object('codigo', 'atividades_sem_notas', 'total', v_atv.total));
  elsif v_atv.com_nota < v_atv.total then
    v_pend := v_pend || jsonb_build_array(jsonb_build_object(
      'codigo', 'atividades_parcial', 'com_nota', v_atv.com_nota, 'total', v_atv.total));
  end if;
  if v_prj.componentes = 0 then
    v_pend := v_pend || jsonb_build_array(jsonb_build_object('codigo', 'projeto_sem_componentes'));
  elsif v_prj.com_nota < v_prj.componentes then
    v_pend := v_pend || jsonb_build_array(jsonb_build_object(
      'codigo', 'projeto_componentes_faltando', 'faltando', to_jsonb(v_prj.faltando)));
  end if;
  if not v_prs.vinculado then
    v_pend := v_pend || jsonb_build_array(jsonb_build_object('codigo', 'presenca_sem_vinculo'));
  elsif v_prs.presenca is null then
    v_pend := v_pend || jsonb_build_array(jsonb_build_object('codigo', 'presenca_indisponivel'));
  end if;

  return query select v_teoria, v_pratica, v_atv.atividades, v_prj.projeto, v_prs.presenca,
                      v_tutoria, v_mentoria, v_final,
                      alunos.conceito_de(v_final), alunos.aprovado_de(v_final),
                      jsonb_array_length(v_pend) = 0, v_pend,
                      v_t_env, v_t_esp, v_m_env, v_m_esp;
end $$;

-- Semesters in which the student appears (enrolment, assignment or evaluation), with the cycle of the enrolment.
create or replace function alunos._historico_calc(p_aluno uuid, p_somente_liberados boolean default false)
returns table (
  semestre_id uuid, semestre text, ciclo text,
  teoria numeric, pratica numeric, atividades numeric, projeto numeric, presenca numeric,
  tutoria numeric, mentoria numeric, final numeric, conceito text, aprovado boolean,
  completo boolean, pendencias jsonb)
language sql
stable
security definer
set search_path = ''
as $$
  select s.id, s.codigo,
         (select c.nome from alunos.matriculas m join alunos.ciclos c on c.id = m.ciclo_id
           where m.aluno_id = p_aluno and m.semestre_id = s.id limit 1),
         n.teoria, n.pratica, n.atividades, n.projeto, n.presenca,
         n.tutoria, n.mentoria, n.final, n.conceito, n.aprovado, n.completo, n.pendencias
    from alunos.semestres s
    cross join lateral alunos._nota_semestre(p_aluno, s.id) n
   where (exists (select 1 from alunos.matriculas m where m.aluno_id = p_aluno and m.semestre_id = s.id)
          or exists (select 1 from alunos.aluno_tutores t where t.aluno_id = p_aluno and t.semestre_id = s.id)
          or exists (select 1 from alunos.avaliacoes a where a.aluno_id = p_aluno and a.semestre_id = s.id))
     and (not p_somente_liberados or alunos.semestre_liberado(s.id))
   order by s.codigo;
$$;

-- Cycle averages = mean of the semester finals, rounded to 1 decimal.
--   Média Básico / Avançado: semesters whose enrolment is in that cycle.
--   Média final: all semesters with a final (any cycle).
create or replace function alunos._medias_ciclo_calc(p_aluno uuid, p_somente_liberados boolean default false)
returns table (media_basico numeric, media_avancado numeric, media_final numeric,
               semestres int, semestres_incompletos int)
language sql
stable
security definer
set search_path = ''
as $$
  select round(avg(h.final) filter (where h.ciclo = 'Básico' and h.final is not null), 1),
         round(avg(h.final) filter (where h.ciclo = 'Avançado' and h.final is not null), 1),
         round(avg(h.final) filter (where h.final is not null), 1),
         (count(*) filter (where h.final is not null))::int,
         (count(*) filter (where h.final is not null and not h.completo))::int
    from alunos._historico_calc(p_aluno, p_somente_liberados) h;
$$;

