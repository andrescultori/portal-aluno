-- Every student that appears in the semester, one row each (feeds the coordination screen and the Excel export).
create or replace function alunos.notas_semestre(p_semestre uuid, p_ate date default null)
returns table (
  aluno_id uuid, nome text,
  teoria numeric, pratica numeric, atividades numeric, projeto numeric, presenca numeric,
  tutoria numeric, mentoria numeric, final numeric, conceito text, aprovado boolean,
  completo boolean, pendencias jsonb,
  tutoria_enviadas int, tutoria_esperados int, mentoria_enviadas int, mentoria_esperados int)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.has_any_role(array['admin', 'coordenacao']) then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  return query
    select a.id, coalesce(a.nome_exibicao, a.nome),
           n.teoria, n.pratica, n.atividades, n.projeto, n.presenca,
           n.tutoria, n.mentoria, n.final, n.conceito, n.aprovado, n.completo, n.pendencias,
           n.tutoria_enviadas, n.tutoria_esperados, n.mentoria_enviadas, n.mentoria_esperados
      from alunos.alunos a
      cross join lateral alunos._nota_semestre(a.id, p_semestre, p_ate) n
     where exists (select 1 from alunos.matriculas m where m.aluno_id = a.id and m.semestre_id = p_semestre)
        or exists (select 1 from alunos.aluno_tutores t where t.aluno_id = a.id and t.semestre_id = p_semestre)
        or exists (select 1 from alunos.avaliacoes v where v.aluno_id = a.id and v.semestre_id = p_semestre)
     order by coalesce(a.nome_exibicao, a.nome);
end $$;

