-- Phase 1B / step 13: computed grades. All numbers are computed here, in SQL, never only in the front end.
--
-- Per (student, semester):
--   teoria    = mean over the Teoria questions   of (mean over evaluators of points, valor 1 ignored)
--   pratica   = same for the Prática questions
--   atividades, projeto, presenca  -> migration 12 (unrounded)
--   tutoria   = round(avg of the non-null, non-zero values among [teoria, pratica, atividades, projeto, presenca], 1)
--   mentoria  = round(mean of the question means of the Mentoria model, 1)   (valor 1 ignored at both levels)
--   final     = round(avg of the non-null, non-zero values among [tutoria, mentoria], 1)   (on the ROUNDED values)
--   conceito  = lookup in alunos.conceitos (editable); aprovado = final >= alunos.notas_config.aprovacao (6.0). No recovery.
-- Rounding is round(numeric, 1): half away from zero = half up for positive values. Components stay unrounded.
-- Only SUBMITTED evaluations (status 'enviada') count. A partial result is always flagged: `completo` is false and
-- `pendencias` lists what is missing; a partial `final` is never definitive.
--
-- Access: the _calc functions are internal (service role only). Staff screens use the wrappers (admin/coordenacao).
-- Students use the my-own-results functions, which return rows only for the logged-in student and only for
-- semesters whose windows have all been released (alunos.semestre_liberado). They never expose an evaluator or a comment.

-- ---------------------------------------------------------------- configuration (editable, audited)
create table if not exists alunos.notas_config (
  id boolean primary key default true check (id),
  aprovacao numeric(3, 1) not null default 6.0 check (aprovacao between 0 and 10)
);
insert into alunos.notas_config (id, aprovacao) values (true, 6.0) on conflict (id) do nothing;

-- Lower bound of each concept; a final belongs to the highest bound it reaches.
-- TODO(owner): compare these thresholds with the Excel workbook; editable by coordenacao/admin without code.
