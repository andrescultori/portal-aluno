  id int generated by default as identity primary key,
  minimo numeric(3, 1) not null unique check (minimo between 0 and 10),
  nome text not null
);
insert into alunos.conceitos (minimo, nome) values
  (0, 'Insatisfatório'), (5, 'Regular'), (7, 'Bom'), (9, 'Excelente')
  on conflict (minimo) do nothing;

