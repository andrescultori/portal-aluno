-- Phase 1A / step 2: reference tables in the `alunos` schema (no people, only domain data).
-- Plans are an own copy of the vocabulary (the Propostas app stays separate).
-- Package values are imported from the spreadsheet, never hard-coded here.

create schema if not exists alunos;

create table if not exists alunos.semestres (
  id uuid primary key default gen_random_uuid(),
  codigo text not null unique check (codigo ~ '^\d{4}-[12]$'),
  inicio date,
  fim date,
  atual boolean not null default false
);
-- at most one "current" semester
create unique index if not exists semestres_atual_uq on alunos.semestres (atual) where atual;

create table if not exists alunos.ciclos (
  id int generated by default as identity primary key,
  nome text not null unique check (nome in ('Básico', 'Avançado', 'Carreira', 'Convênio'))
);

create table if not exists alunos.modulos (
  id int generated by default as identity primary key,
  ciclo_id int not null references alunos.ciclos (id) on delete cascade,
  ordem smallint not null,
  nome text not null,
  unique (ciclo_id, ordem)
);

create table if not exists alunos.casas (
  id int generated by default as identity primary key,
  nome text not null unique
);

create table if not exists alunos.planos (
  codigo text primary key,
  ordem smallint not null,
  convenio boolean not null default false,
  ativo boolean not null default true
);

create table if not exists alunos.pacotes (
  id int generated by default as identity primary key,
  nome text not null unique,
  valor numeric(12, 2),
  ativo boolean not null default true
);

-- Deny by default until the RLS migration adds the policies.
alter table alunos.semestres enable row level security;
alter table alunos.ciclos enable row level security;
alter table alunos.modulos enable row level security;
alter table alunos.casas enable row level security;
alter table alunos.planos enable row level security;
alter table alunos.pacotes enable row level security;

revoke all on alunos.semestres, alunos.ciclos, alunos.modulos, alunos.casas, alunos.planos, alunos.pacotes
  from anon;

-- Reference seeds (domain vocabulary only)
insert into alunos.ciclos (nome) values ('Básico'), ('Avançado'), ('Carreira'), ('Convênio')
  on conflict (nome) do nothing;

insert into alunos.modulos (ciclo_id, ordem, nome)
select c.id, m.ordem, m.nome
  from (values
    ('Básico', 1, 'Universidade'),
    ('Básico', 2, 'Mercado de Trabalho'),
    ('Básico', 3, 'Missões Urbanas'),
    ('Básico', 4, 'Missões Transculturais'),
    ('Avançado', 1, 'Gestão de Projetos'),
    ('Avançado', 2, 'Gestão de Carreira')
  ) as m (ciclo, ordem, nome)
  join alunos.ciclos c on c.nome = m.ciclo
on conflict (ciclo_id, ordem) do nothing;

insert into alunos.casas (nome) values
  ('Casa Amarela'), ('Casa Meninos'), ('Casa de Madeira'), ('Apt. Salinas'), ('FORA')
  on conflict (nome) do nothing;

insert into alunos.planos (codigo, ordem, convenio) values
  ('Completo', 1, false), ('Curso', 2, false), ('Convênio', 3, true),
  ('Alimentação', 4, false), ('Moradia', 5, false), ('Equipe', 6, false)
  on conflict (codigo) do nothing;

insert into alunos.pacotes (nome) values ('Missão'), ('Propósito'), ('Vocação'), ('Reino')
  on conflict (nome) do nothing;
