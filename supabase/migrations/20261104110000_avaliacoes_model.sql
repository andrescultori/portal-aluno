-- ---------------------------------------------------------------- identity / assignment helpers
-- The logged-in user's row in the team directory (matched by the verified e-mail).
create or replace function alunos.minha_equipe_id()
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select e.id
    from alunos.equipe e
   where e.ativo and e.email = lower(coalesce(auth.jwt() ->> 'email', ''))
   limit 1;
$$;

-- May the logged-in user evaluate this student in this category/semester AS this team member?
--   tutoria : explicit alunos.aluno_tutores row ('tutoria')
--   mentoria: explicit aluno_tutores row ('mentoria'), or house leader (role lider_casa + equipe_casas
--             containing the student's house)
-- Emissor-only users are not staff and never qualify.
create or replace function alunos.pode_avaliar(p_aluno uuid, p_semestre uuid, p_categoria text, p_equipe uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_staff()
     and p_equipe is not null
     and p_equipe = alunos.minha_equipe_id()
     and (
       exists (select 1 from alunos.aluno_tutores t
                where t.aluno_id = p_aluno and t.semestre_id = p_semestre
                  and t.equipe_id = p_equipe and t.categoria = p_categoria)
       or (p_categoria = 'mentoria'
           and public.has_role('lider_casa')
           and exists (select 1
                         from alunos.alunos a
                         join alunos.equipe_casas ec on ec.casa_id = a.casa_id
                        where a.id = p_aluno and ec.equipe_id = p_equipe))
     );
$$;

create or replace function alunos.janela_aberta(p_semestre uuid, p_categoria text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from alunos.avaliacao_janelas j
     where j.semestre_id = p_semestre and j.categoria = p_categoria
       and j.abre_em is not null and j.fecha_em is not null
       and now() >= j.abre_em and now() <= j.fecha_em);
$$;

