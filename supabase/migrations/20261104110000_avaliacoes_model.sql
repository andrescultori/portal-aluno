-- Phase 1B / step 11: evaluation module — versioned question bank, evaluations, windows, comments.
--
-- Visibility (enforced by RLS, never by the UI):
--   * an evaluator reads/writes only their OWN evaluations (answers + comments) of students they are assigned to;
--   * coordenacao / admin read and edit everything, including comments;
--   * students, secretaria, financeiro and emissor-only users read NO raw evaluation row. Students get only
--     their own aggregates, after release, through the functions of migration 13.
-- Comments live in their own table so a `select *` on avaliacoes can never leak them.
-- Scores are computed in the database (migration 13); this migration only stores and validates.

-- ---------------------------------------------------------------- audit helper (extra registro_id fallbacks)
create or replace function alunos.audit_row()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_old jsonb;
  v_new jsonb;
  v_row jsonb;
  v_id text;
begin
  if tg_op in ('UPDATE', 'DELETE') then v_old := alunos.audit_mask(to_jsonb(old)); end if;
  if tg_op in ('INSERT', 'UPDATE') then v_new := alunos.audit_mask(to_jsonb(new)); end if;

  -- ignore no-op updates (only the touch timestamp changed)
  if tg_op = 'UPDATE' and (v_old - 'atualizado_em') = (v_new - 'atualizado_em') then
    return null;
  end if;

  v_row := coalesce(v_new, v_old);
  v_id := coalesce(
    v_row ->> 'aluno_id',
    v_row ->> 'id',
    v_row ->> 'avaliacao_id',
    nullif(concat_ws(':', v_row ->> 'equipe_id', v_row ->> 'casa_id'), ''),
    nullif(concat_ws(':', v_row ->> 'semestre_id', v_row ->> 'categoria'), ''));

  insert into alunos.auditoria (usuario, usuario_email, tabela, operacao, registro_id, antes, depois)
  values (auth.uid(), nullif(lower(coalesce(auth.jwt() ->> 'email', '')), ''),
          tg_table_name, tg_op, v_id, v_old, v_new);
  return null;
end $$;
revoke all on function alunos.audit_row() from public, anon, authenticated;

