-- Can the logged-in user change this evaluation's answers/comments right now?
--   coordenacao/admin: always (audited); evaluator: own, still a draft, assigned, window open.
create or replace function alunos.avaliacao_editavel(p_avaliacao uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from alunos.avaliacoes a
     where a.id = p_avaliacao
       and (public.has_any_role(array['admin', 'coordenacao'])
            or (a.status = 'rascunho'
                and a.avaliador_equipe_id = alunos.minha_equipe_id()
                and alunos.janela_aberta(a.semestre_id, a.categoria)
                and alunos.pode_avaliar(a.aluno_id, a.semestre_id, a.categoria, a.avaliador_equipe_id))));
$$;

-- ---------------------------------------------------------------- guards
-- A model that already has evaluations is frozen: wording changes need a new version.
create or replace function alunos.tg_modelo_imutavel()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_ids int[] := '{}';
begin
  if tg_table_name = 'avaliacao_modelos' then
    if tg_op = 'INSERT' then return new; end if;
    -- activating/deactivating a used model is allowed; anything else is not
    if tg_op = 'UPDATE' and
       (new.categoria, new.versao, new.rotulo_observacoes, new.ajuda_observacoes, new.rotulo_desenvolvimento)
       is not distinct from
       (old.categoria, old.versao, old.rotulo_observacoes, old.ajuda_observacoes, old.rotulo_desenvolvimento)
    then return new; end if;
    v_ids := array[old.id];
  elsif tg_table_name = 'avaliacao_grupos' then
    if tg_op in ('UPDATE', 'DELETE') then v_ids := v_ids || old.modelo_id; end if;
    if tg_op in ('INSERT', 'UPDATE') then v_ids := v_ids || new.modelo_id; end if;
  else
    if tg_op in ('UPDATE', 'DELETE') then
      v_ids := v_ids || (select g.modelo_id from alunos.avaliacao_grupos g where g.id = old.grupo_id);
    end if;
    if tg_op in ('INSERT', 'UPDATE') then
      v_ids := v_ids || (select g.modelo_id from alunos.avaliacao_grupos g where g.id = new.grupo_id);
    end if;
  end if;

  if exists (select 1 from alunos.avaliacoes where modelo_id = any (v_ids)) then
    raise exception 'This question model already has evaluations; create a new version instead'
      using errcode = '55006';
  end if;
  return case when tg_op = 'DELETE' then old else new end;
end $$;

-- Evaluation row rules: fixed keys, status 'enviada' only through alunos.enviar_avaliacao().
create or replace function alunos.tg_avaliacao_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' and
     (new.semestre_id, new.aluno_id, new.avaliador_equipe_id, new.modelo_id, new.categoria)
     is distinct from
     (old.semestre_id, old.aluno_id, old.avaliador_equipe_id, old.modelo_id, old.categoria) then
    raise exception 'Semester, student, evaluator and model of an evaluation cannot be changed'
      using errcode = '42501';
  end if;

  if new.status = 'enviada'
     and (tg_op = 'INSERT' or old.status is distinct from 'enviada')
     and auth.uid() is not null
     and coalesce(current_setting('app.avaliacao_enviar', true), '') <> 'on' then
    raise exception 'Use alunos.enviar_avaliacao() to submit an evaluation' using errcode = '42501';
  end if;

  if new.status = 'rascunho' then new.enviada_em := null; end if;
  return new;
end $$;

-- Answers/comments: the model must match, and the evaluation must be editable by the caller.
create or replace function alunos.tg_avaliacao_filho_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_avaliacao uuid := case when tg_op = 'DELETE' then old.avaliacao_id else new.avaliacao_id end;
begin
  if tg_op = 'UPDATE' and new.avaliacao_id is distinct from old.avaliacao_id then
    raise exception 'The evaluation of an answer cannot be changed' using errcode = '42501';
  end if;

  -- cascade delete: the parent evaluation is already gone, nothing left to protect
  if tg_op = 'DELETE' and not exists (select 1 from alunos.avaliacoes where id = v_avaliacao) then
    return old;
  end if;

  if auth.uid() is not null and not alunos.avaliacao_editavel(v_avaliacao) then
    raise exception 'This evaluation is locked (submitted, window closed or not assigned to you)'
      using errcode = '42501';
  end if;

  if tg_table_name = 'avaliacao_respostas' and tg_op <> 'DELETE' then
    if tg_op = 'UPDATE' and new.pergunta_id is distinct from old.pergunta_id then
      raise exception 'The question of an answer cannot be changed' using errcode = '42501';
    end if;
    if (select g.modelo_id from alunos.avaliacao_perguntas p
          join alunos.avaliacao_grupos g on g.id = p.grupo_id where p.id = new.pergunta_id)
       is distinct from (select a.modelo_id from alunos.avaliacoes a where a.id = new.avaliacao_id) then
      raise exception 'The question does not belong to the evaluation model' using errcode = '23514';
    end if;
  end if;

  return case when tg_op = 'DELETE' then old else new end;
end $$;

