-- ---------------------------------------------------------------- question bank (versioned)
create table if not exists alunos.avaliacao_modelos (
  id int generated by default as identity primary key,
  categoria text not null check (categoria in ('tutoria', 'mentoria')),
  versao int not null check (versao > 0),
  ativo boolean not null default false,
  rotulo_observacoes text not null,
  ajuda_observacoes text,
  rotulo_desenvolvimento text not null,
  criado_em timestamptz not null default now(),
  unique (categoria, versao),
  unique (id, categoria)
);
-- at most one active model per category
create unique index if not exists avaliacao_modelos_ativo_uq on alunos.avaliacao_modelos (categoria) where ativo;

create table if not exists alunos.avaliacao_grupos (
  id int generated by default as identity primary key,
  modelo_id int not null references alunos.avaliacao_modelos (id) on delete cascade,
  ordem smallint not null,
  codigo text not null,
  nome text not null,
  unique (modelo_id, ordem),
  unique (modelo_id, codigo)
);

create table if not exists alunos.avaliacao_perguntas (
  id int generated by default as identity primary key,
  grupo_id int not null references alunos.avaliacao_grupos (id) on delete cascade,
  ordem smallint not null,
  texto text not null,
  unique (grupo_id, ordem)
);

-- ---------------------------------------------------------------- windows
-- Dates are entered by coordenacao in the UI; nothing is hard-coded.
create table if not exists alunos.avaliacao_janelas (
  semestre_id uuid not null references alunos.semestres (id) on delete cascade,
  categoria text not null check (categoria in ('tutoria', 'mentoria')),
  abre_em timestamptz,
  fecha_em timestamptz,
  liberada_em timestamptz,   -- from this moment students may see their results
  primary key (semestre_id, categoria),
  check (abre_em is null or fecha_em is null or abre_em < fecha_em)
);

-- ---------------------------------------------------------------- evaluations
-- One evaluation per evaluator per student per category and semester. `categoria` is a column
-- (checked against the model with a composite FK) so a new model version can never open a second slot.
create table if not exists alunos.avaliacoes (
  id uuid primary key default gen_random_uuid(),
  semestre_id uuid not null references alunos.semestres (id) on delete restrict,
  aluno_id uuid not null references alunos.alunos (id) on delete cascade,
  avaliador_equipe_id uuid not null references alunos.equipe (id) on delete restrict,
  modelo_id int not null,
  categoria text not null,
  status text not null default 'rascunho' check (status in ('rascunho', 'enviada')),
  enviada_em timestamptz,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  foreign key (modelo_id, categoria) references alunos.avaliacao_modelos (id, categoria),
  unique (semestre_id, aluno_id, avaliador_equipe_id, categoria)
);
create index if not exists avaliacoes_aluno_ix on alunos.avaliacoes (aluno_id, semestre_id);
create index if not exists avaliacoes_avaliador_ix on alunos.avaliacoes (avaliador_equipe_id, semestre_id);
create index if not exists avaliacoes_modelo_ix on alunos.avaliacoes (modelo_id);

create table if not exists alunos.avaliacao_respostas (
  avaliacao_id uuid not null references alunos.avaliacoes (id) on delete cascade,
  pergunta_id int not null references alunos.avaliacao_perguntas (id),
  valor smallint not null check (valor between 1 and 5),
  primary key (avaliacao_id, pergunta_id)
);

-- Free text, in its own table with its own (stricter) RLS.
create table if not exists alunos.avaliacao_comentarios (
  avaliacao_id uuid primary key references alunos.avaliacoes (id) on delete cascade,
  observacoes text,
  desenvolvimento text,
  atualizado_em timestamptz not null default now()
);

