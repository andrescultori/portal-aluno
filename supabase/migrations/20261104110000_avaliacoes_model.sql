-- ---------------------------------------------------------------- submit
-- Validates and submits. Rules: every question answered; any answer below 4 (Bom), including
-- "cannot answer", requires the observation text. Evaluators also need an open window and the
-- assignment; coordenacao/admin skip those two checks (override) but not the content rules.
create or replace function alunos.enviar_avaliacao(p_avaliacao uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  a alunos.avaliacoes%rowtype;
  v_total int;
  v_respondidas int;
  -- coordenacao/admin override the window/assignment checks; so does a call without an end-user JWT
  -- (service role, SQL Editor)
  v_override boolean := public.has_any_role(array['admin', 'coordenacao']) or auth.uid() is null;
begin
  select * into a from alunos.avaliacoes where id = p_avaliacao for update;
  if not found then
    raise exception 'Evaluation not found' using errcode = 'P0002';
  end if;

  if not v_override then
    if not alunos.pode_avaliar(a.aluno_id, a.semestre_id, a.categoria, a.avaliador_equipe_id) then
      raise exception 'Not allowed' using errcode = '42501';
    end if;
    if a.status = 'enviada' then
      raise exception 'This evaluation was already submitted' using errcode = '55000';
    end if;
    if not alunos.janela_aberta(a.semestre_id, a.categoria) then
      raise exception 'The evaluation window is closed' using errcode = '55000';
    end if;
  end if;

  select count(*) into v_total
    from alunos.avaliacao_perguntas p
    join alunos.avaliacao_grupos g on g.id = p.grupo_id
   where g.modelo_id = a.modelo_id;
  select count(*) into v_respondidas from alunos.avaliacao_respostas where avaliacao_id = a.id;
  if v_respondidas < v_total then
    raise exception 'Answer all questions before submitting (% of %)', v_respondidas, v_total
      using errcode = '22023';
  end if;

  if exists (select 1 from alunos.avaliacao_respostas where avaliacao_id = a.id and valor < 4)
     and nullif(btrim(coalesce((select observacoes from alunos.avaliacao_comentarios
                                 where avaliacao_id = a.id), '')), '') is null then
    raise exception 'The observation is required when any answer is below Bom' using errcode = '22023';
  end if;

  if a.status <> 'enviada' then
    perform set_config('app.avaliacao_enviar', 'on', true);
    update alunos.avaliacoes set status = 'enviada', enviada_em = now() where id = a.id;
    perform set_config('app.avaliacao_enviar', '', true);
  end if;
end $$;

-- ---------------------------------------------------------------- bank versioning (coordenacao/admin)
create or replace function alunos.nova_versao_modelo(p_categoria text)
returns int
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_src alunos.avaliacao_modelos%rowtype;
  v_novo int;
  g record;
  v_grupo int;
begin
  if not public.has_any_role(array['admin', 'coordenacao']) then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  select * into v_src from alunos.avaliacao_modelos
   where categoria = p_categoria order by versao desc limit 1;
  if not found then
    raise exception 'No model for category %', p_categoria using errcode = 'P0002';
  end if;

  insert into alunos.avaliacao_modelos (categoria, versao, ativo, rotulo_observacoes, ajuda_observacoes, rotulo_desenvolvimento)
  values (p_categoria, v_src.versao + 1, false, v_src.rotulo_observacoes, v_src.ajuda_observacoes, v_src.rotulo_desenvolvimento)
  returning id into v_novo;

  for g in select * from alunos.avaliacao_grupos where modelo_id = v_src.id order by ordem loop
    insert into alunos.avaliacao_grupos (modelo_id, ordem, codigo, nome)
    values (v_novo, g.ordem, g.codigo, g.nome) returning id into v_grupo;
    insert into alunos.avaliacao_perguntas (grupo_id, ordem, texto)
    select v_grupo, p.ordem, p.texto from alunos.avaliacao_perguntas p where p.grupo_id = g.id;
  end loop;
  return v_novo;
end $$;

create or replace function alunos.ativar_modelo(p_modelo int)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_cat text;
begin
  if not public.has_any_role(array['admin', 'coordenacao']) then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  select categoria into v_cat from alunos.avaliacao_modelos where id = p_modelo;
  if v_cat is null then
    raise exception 'Model not found' using errcode = 'P0002';
  end if;
  update alunos.avaliacao_modelos set ativo = false where categoria = v_cat and ativo and id <> p_modelo;
  update alunos.avaliacao_modelos set ativo = true where id = p_modelo;
end $$;

-- ---------------------------------------------------------------- "my students" for the evaluator screen
create or replace function alunos.meus_alunos_avaliar(p_semestre uuid)
returns table (
  aluno_id uuid, nome text, casa text, categoria text,
  avaliacao_id uuid, situacao text, respondidas int, total int,
  janela_aberta boolean, abre_em timestamptz, fecha_em timestamptz)
language sql
stable
security definer
set search_path = ''
as $$
  with me as (
    select alunos.minha_equipe_id() as id
  ),
  alvos as (
    select t.aluno_id, t.categoria
      from alunos.aluno_tutores t, me
     where t.semestre_id = p_semestre and t.equipe_id = me.id and public.is_staff()
    union
    select a.id, 'mentoria'
      from alunos.alunos a
      join alunos.equipe_casas ec on ec.casa_id = a.casa_id, me
     where ec.equipe_id = me.id and public.has_role('lider_casa') and public.is_staff()
  )
  select al.aluno_id,
         coalesce(a.nome_exibicao, a.nome),
         c.nome,
         al.categoria,
         av.id,
         case when av.id is null then 'nao_iniciada' else av.status end,
         coalesce((select count(*)::int from alunos.avaliacao_respostas r where r.avaliacao_id = av.id), 0),
         (select count(*)::int
            from alunos.avaliacao_perguntas p
            join alunos.avaliacao_grupos g on g.id = p.grupo_id
           where g.modelo_id = coalesce(av.modelo_id,
                 (select m.id from alunos.avaliacao_modelos m where m.categoria = al.categoria and m.ativo))),
         alunos.janela_aberta(p_semestre, al.categoria),
         j.abre_em,
         j.fecha_em
    from alvos al
    join alunos.alunos a on a.id = al.aluno_id
    left join alunos.casas c on c.id = a.casa_id
    left join alunos.avaliacoes av
           on av.semestre_id = p_semestre and av.aluno_id = al.aluno_id
          and av.categoria = al.categoria and av.avaliador_equipe_id = (select id from me)
    left join alunos.avaliacao_janelas j on j.semestre_id = p_semestre and j.categoria = al.categoria
   order by coalesce(a.nome_exibicao, a.nome), al.categoria;
$$;

