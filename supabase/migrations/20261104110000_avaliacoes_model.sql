  with check (
    public.has_any_role(array['admin', 'coordenacao'])
    or (status = 'rascunho'
        and avaliador_equipe_id = alunos.minha_equipe_id()
        and alunos.pode_avaliar(aluno_id, semestre_id, categoria, avaliador_equipe_id)
        and alunos.janela_aberta(semestre_id, categoria)
        and exists (select 1 from alunos.avaliacao_modelos m where m.id = modelo_id and m.ativo)));

